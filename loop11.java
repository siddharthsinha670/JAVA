
import java.util.Scanner;

public class loop11 {
    public static void main(String args[])
    {
        Scanner x = new Scanner(System.in);
        int fact=0;
        int n = x.nextInt();
        for(int a=1;a<=n;a++)
        {
            fact = fact*1;
            System.out.println(fact);
        }
    }
    
}