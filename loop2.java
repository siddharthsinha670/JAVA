//Print numbers from 10 to 1 decreasing order

import java.util.Scanner;
public class loop2
{
    public static void main(String args[])
    {
        Scanner x = new Scanner(System.in);
        int i;
        for(i=10;i>=1;i--)         
        {
        System.out.println("  "+i);
        } 
        x.close();
    
    }
}